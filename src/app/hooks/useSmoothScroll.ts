import { useEffect, useRef } from 'react';
import Lenis from 'lenis';

// Buttery inertia scroll for the customer store. Returns a ref so callers
// (e.g. route-change scroll-to-top) can drive Lenis instead of window.scrollTo,
// which would otherwise fight Lenis's own scroll position each frame.
export function useSmoothScroll() {
  const lenisRef = useRef<Lenis | null>(null);

  useEffect(() => {
    const lenis = new Lenis({
      duration: 1.1,
      easing: (t: number) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
    });
    lenisRef.current = lenis;

    let rafId: number;
    function raf(time: number) {
      lenis.raf(time);
      rafId = requestAnimationFrame(raf);
    }
    rafId = requestAnimationFrame(raf);

    return () => {
      cancelAnimationFrame(rafId);
      lenis.destroy();
      lenisRef.current = null;
    };
  }, []);

  return lenisRef;
}
